// Single-line block font for stitched notes. Each glyph is a list of strokes
// (polylines) the needle follows. Units: cap height is 10, y points down.

type Pt = [number, number];
export type Glyph = { width: number; strokes: Pt[][] };

/** Points along an ellipse from angle a0 to a1 (degrees; 0 = right, 90 = down). */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number): Pt[] {
  const steps = Math.max(4, Math.ceil(Math.abs(a1 - a0) / 15));
  const pts: Pt[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return pts;
}

const g = (width: number, ...strokes: Pt[][]): Glyph => ({ width, strokes });

